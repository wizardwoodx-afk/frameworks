"""Draft a SECURITY.md from what the scanner actually found.

The goal is a policy document that reflects this repository rather than a generic
template: the categories that matter here, the reporting channel, and the
expectations the code already encodes.
"""
from __future__ import annotations

from pathlib import Path
from typing import Sequence

from .scanner import Finding, ScanReport

_TEMPLATE = """# Security policy

## Supported versions

| Version | Supported |
| ------- | --------- |
| latest minor | yes |
| older releases | best effort, security fixes only |

## Reporting a vulnerability

Please report suspected vulnerabilities privately — do not open a public issue.

- Contact: {contact}
- Include: affected version, a reproduction (minimal where possible), and impact.
- Acknowledgement within {sla} working days; we will agree a disclosure timeline with you.

## Scope

This repository contains:

{scope}

## What we treat as a security issue

{issues}

## Automated checks in this repository

- **Dependency hygiene**: every dependency is pinned; typosquats and ranges are rejected in CI.
- **Static scanning**: the built-in scanner runs on each change; SARIF results are uploaded
  to code scanning so new findings are reviewable in the pull request.
- **Secret hygiene**: credentials are never committed; configuration comes from the
  environment or a secret manager.
- **Prompt integrity**: system prompts are audited for injection resistance and the audit
  is recorded, so a regression in guidance fails the build rather than degrading silently.

## Out of scope

- Denial of service through resource exhaustion on self-hosted deployments.
- Vulnerabilities in third-party dependencies without a viable upstream fix (we will pin,
  patch or remove as appropriate).

_Generated by RISTER from a scan of this repository on {scanned} ({files} files,
{findings} findings). Review before publishing._
"""


def _coerce(report: "ScanReport | Sequence[Finding]") -> ScanReport:
    """Accept a scan report or a bare list of findings."""
    if isinstance(report, ScanReport):
        return report
    findings = list(report)
    return ScanReport(findings=findings, files_scanned=1)


def _scope(report: ScanReport) -> str:
    if not report.findings:
        return "- Source code and configuration in this repository."
    paths = sorted({Path(f.path).suffix or "<no extension>" for f in report.findings})
    return "\n".join(f"- `{p}` sources" for p in paths)


def _issues(report: ScanReport) -> str:
    categories: dict[str, list[str]] = {}
    for finding in report.findings:
        categories.setdefault(finding.rule, []).append(finding.title)
    if not categories:
        return (
            "- Authentication and authorisation flaws\n"
            "- Injection (SQL, command, template, prompt)\n"
            "- Secret exposure\n"
            "- Unsafe deserialisation or dynamic evaluation"
        )
    lines = []
    for rule_id in sorted(categories):
        lines.append(f"- **{rule_id}** — {categories[rule_id][0]}")
    return "\n".join(lines)


def draft_security_policy(
    report: "ScanReport | Sequence[Finding]",
    *,
    contact: str = "security@example.invalid",
    sla: int = 3,
) -> str:
    """Return a SECURITY.md draft tailored to a scan report (or findings list)."""
    import datetime as _dt

    report = _coerce(report)
    return _TEMPLATE.format(
        contact=contact,
        sla=sla,
        scope=_scope(report),
        issues=_issues(report),
        scanned=_dt.date.today().isoformat(),
        files=report.files_scanned,
        findings=len(report.findings),
    )


def write_security_policy(
    report: "ScanReport | Sequence[Finding]",
    path: str | Path,
    *,
    contact: str = "security@example.invalid",
    sla: int = 3,
    force: bool = False,
) -> Path:
    """Write the draft. Existing files are preserved unless ``force``."""
    target = Path(path)
    if target.exists() and not force:
        raise FileExistsError(
            f"{target} already exists; pass force=True after reviewing the draft"
        )
    target.write_text(
        draft_security_policy(_coerce(report), contact=contact, sla=sla), encoding="utf-8"
    )
    return target


__all__ = ["draft_security_policy", "write_security_policy"]
